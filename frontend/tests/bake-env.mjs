// Bake the environment light of the WebGL 3D view into src/ui/roomEnv.ts, so the software renderer
// (used when the browser has no WebGL) reflects the same room as the GPU view.
//
//   npm run bake-env
//
// Renders three.js's RoomEnvironment through PMREMGenerator exactly as view3d.ts does, then samples
// it with three's own textureCubeUV() at several roughness levels into small lat-long maps.
// Needs Google Chrome or Chromium (set CHROME=/path/to/chrome if it isn't found).

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright-core";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const outFile = join(root, "src/ui/roomEnv.ts");
const chromePath =
  process.env.CHROME ??
  ["/usr/bin/google-chrome-stable", "/usr/bin/google-chrome", "/usr/bin/chromium", "/usr/bin/chromium-browser",
   "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"].find(existsSync);

const W = 64;
const H = 32;
const ROUGHNESS = [0.15, 0.22, 0.3, 0.45, 0.65, 1];

const page = `<!doctype html><meta charset="utf-8">
<script type="importmap">{"imports": {"three": "/three/build/three.module.js", "three/addons/": "/three/examples/jsm/"}}</script>
<script type="module">
import * as THREE from "three";
import { RoomEnvironment } from "three/addons/environments/RoomEnvironment.js";
try {
  const renderer = new THREE.WebGLRenderer();
  const env = new THREE.PMREMGenerator(renderer).fromScene(new RoomEnvironment(), 0.04); // as view3d.ts
  const maxMip = Math.log2(env.height) - 2; // as three's WebGLProgram generateCubeUVSize()
  const material = new THREE.ShaderMaterial({
    defines: {
      ENVMAP_TYPE_CUBE_UV: "",
      CUBEUV_TEXEL_WIDTH: 1 / (3 * Math.max(2 ** maxMip, 7 * 16)),
      CUBEUV_TEXEL_HEIGHT: 1 / env.height,
      CUBEUV_MAX_MIP: maxMip + ".0",
    },
    uniforms: { envMap: { value: env.texture }, roughness: { value: 0 } },
    vertexShader: "varying vec2 vUv; void main() { vUv = uv; gl_Position = vec4(position.xy, 0.0, 1.0); }",
    fragmentShader: \`
      #include <common>
      #include <cube_uv_reflection_fragment>
      uniform sampler2D envMap;
      uniform float roughness;
      varying vec2 vUv;
      void main() {
        float phi = vUv.x * 2.0 * PI - PI;
        float theta = vUv.y * PI;
        vec3 dir = vec3(sin(theta) * sin(phi), cos(theta), sin(theta) * cos(phi));
        gl_FragColor = vec4(textureCubeUV(envMap, dir, roughness).rgb, 1.0);
      }\`,
  });
  const scene = new THREE.Scene();
  scene.add(new THREE.Mesh(new THREE.PlaneGeometry(2, 2), material));
  const camera = new THREE.Camera();
  const target = new THREE.WebGLRenderTarget(${W}, ${H}, { type: THREE.FloatType });
  const maps = [];
  for (const r of ${JSON.stringify(ROUGHNESS)}) {
    material.uniforms.roughness.value = r;
    renderer.setRenderTarget(target);
    renderer.render(scene, camera);
    const px = new Float32Array(${W * H} * 4);
    renderer.readRenderTargetPixels(target, 0, 0, ${W}, ${H}, px);
    maps.push(Array.from(px));
  }
  window.result = { maps };
} catch (err) {
  window.result = { error: String(err) };
}
</script>`;

const browser = await chromium.launch({ executablePath: chromePath, headless: true });
try {
  const tab = await browser.newPage();
  await tab.route("http://bake.local/**", (route) => {
    const path = new URL(route.request().url()).pathname;
    if (path === "/") return route.fulfill({ body: page, contentType: "text/html" });
    return route.fulfill({ body: readFileSync(join(root, "node_modules", path)), contentType: "text/javascript" });
  });
  await tab.goto("http://bake.local/");
  await tab.waitForFunction(() => window.result, null, { timeout: 60_000 });
  const result = await tab.evaluate(() => window.result);
  if (result.error) throw new Error(result.error);

  // The room is white and gray, so one channel is enough. Store log2 as 16-bit: 2^-16 .. 2^16.
  const bytes = new Uint8Array(ROUGHNESS.length * W * H * 2);
  let k = 0;
  let worstTint = 0;
  for (const px of result.maps) {
    for (let i = 0; i < W * H; i++) {
      const [r, g, b] = [px[i * 4], px[i * 4 + 1], px[i * 4 + 2]];
      worstTint = Math.max(worstTint, Math.abs(r - g) / (g + 1e-6), Math.abs(b - g) / (g + 1e-6));
      const q = Math.min(65535, Math.max(0, Math.round((Math.log2(Math.max(g, 2 ** -16)) + 16) * 2048)));
      bytes[k++] = q & 255;
      bytes[k++] = q >> 8;
    }
  }
  if (worstTint > 0.02) throw new Error(`environment is tinted (${(worstTint * 100).toFixed(1)}%); store RGB instead`);
  const b64 = Buffer.from(bytes).toString("base64");
  writeFileSync(
    outFile,
    `// Generated by tests/bake-env.mjs (npm run bake-env); do not edit.
// The light that the WebGL 3D view's metal reflects: three.js's RoomEnvironment through PMREMGenerator,
// sampled with textureCubeUV() at several roughness levels. Lat-long maps, ${W} x ${H}, rows from +y down
// (theta = (row + 0.5) / ${H} * pi), columns phi = (col + 0.5) / ${W} * 2pi - pi, direction
// (sin theta sin phi, cos theta, sin theta cos phi). Values are log2(radiance) + 16 in 1/2048 steps.

export const ENV_W = ${W};
export const ENV_H = ${H};
export const ENV_ROUGHNESS = ${JSON.stringify(ROUGHNESS)};
export const ENV_DATA =
${b64.match(/.{1,100}/g).map((l) => `  "${l}"`).join(" +\n")};
`,
  );
  console.log(`wrote ${outFile} (${bytes.length} bytes of maps)`);
} finally {
  await browser.close();
}
